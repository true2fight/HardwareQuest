/**
 * Calculates grade according to the 12-point Ukrainian school assessment criteria
 * @param {number} pointsEarned Total earned points
 * @param {number} maxPoints Maximum possible points
 * @returns {Object} Score details with 12-point grade, percentage, and level description
 */
function calculateUkrainianGrade(pointsEarned, maxPoints) {
  if (!maxPoints || maxPoints <= 0) maxPoints = 100;
  const percentage = Math.round((pointsEarned / maxPoints) * 100);

  let grade = 1;
  let level = "Початковий рівень";
  let color = "#ef4444"; // red
  let commentary = "Потрібно повторити теоретичний матеріал з апаратного забезпечення.";

  if (percentage >= 93) {
    grade = 12;
    level = "Високий рівень (Відмінно)";
    color = "#10b981";
    commentary = "Блискучий результат! Досконале знання всіх компонентів та принципів роботи ПК!";
  } else if (percentage >= 85) {
    grade = 11;
    level = "Високий рівень (Відмінно)";
    color = "#10b981";
    commentary = "Відмінні знання апаратного забезпечення! Ти справжній комп'ютерний інженер!";
  } else if (percentage >= 78) {
    grade = 10;
    level = "Високий рівень";
    color = "#10b981";
    commentary = "Дуже гарний результат! Матеріал засвоєно на високому рівні.";
  } else if (percentage >= 70) {
    grade = 9;
    level = "Достатній рівень";
    color = "#3b82f6";
    commentary = "Добре! Ти впевнено орієнтуєшся в комплектуючих та їхніх властивостях.";
  } else if (percentage >= 62) {
    grade = 8;
    level = "Достатній рівень";
    color = "#3b82f6";
    commentary = "Добрий результат! Більшість завдань виконано правильно.";
  } else if (percentage >= 54) {
    grade = 7;
    level = "Достатній рівень";
    color = "#3b82f6";
    commentary = "Достатній рівень знань. Зверни увагу на характеристики накопичувачів і мережі.";
  } else if (percentage >= 46) {
    grade = 6;
    level = "Середній рівень";
    color = "#f59e0b";
    commentary = "Середній рівень. Рекомендуємо ще раз переглянути теоретичний блок квесту.";
  } else if (percentage >= 38) {
    grade = 5;
    level = "Середній рівень";
    color = "#f59e0b";
    commentary = "Матеріал засвоєно частково. Є прогалини в розумінні функцій пристроїв.";
  } else if (percentage >= 30) {
    grade = 4;
    level = "Середній рівень";
    color = "#f59e0b";
    commentary = "Базові поняття знайомі, але для впевненості варто пройти тренажер повторно.";
  } else if (percentage >= 20) {
    grade = 3;
    level = "Початковий рівень";
    color = "#ef4444";
    commentary = "Початковий рівень. Повтори відмінності між внутрішньою та зовнішньою пам'яттю.";
  } else if (percentage >= 10) {
    grade = 2;
    level = "Початковий рівень";
    color = "#ef4444";
    commentary = "Початковий рівень. Не засмучуйся, прочитай підказки і спробуй ще раз!";
  } else {
    grade = 1;
    level = "Початковий рівень";
    color = "#ef4444";
    commentary = "Спробуй пройти квест знову з уважним читанням навчальних карток!";
  }

  return {
    percentage,
    grade,
    level,
    color,
    commentary,
    pointsEarned,
    maxPoints
  };
}

